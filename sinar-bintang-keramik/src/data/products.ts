export const products: readonly Product[] = [
  ...inputs.filter((p) => p.featured),
  ...inputs.filter((p) => !p.featured),
].map(withImage);

export const formatRupiah = (n: number) =>
  new Intl.NumberFormat('id-ID', {
    style: 'currency',
    currency: 'IDR',
    maximumFractionDigits: 0,
  }).format(n);
